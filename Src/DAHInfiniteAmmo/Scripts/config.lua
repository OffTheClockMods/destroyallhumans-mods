    start_on = true,
    -- Key that switches it off and on, in quotes: "F7", "PAGEUP", or a combination like "CTRL+F7". "" = no key.
    -- The game uses no F-keys except F11 (fullscreen); F12 is Steam's screenshot key.
    hotkey = "F7",
    -- true = ammo weapons (Disintegrator Ray, Ion Detonator, Anal Probe, saucer ammo weapons) never run out.
    ammo = true,
    -- true = energy weapons (Zap-O-Matic, the saucer's death ray) never run dry. false = they drain and recharge
    -- as normal.
    charge = true,
}
